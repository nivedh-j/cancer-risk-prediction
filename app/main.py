import streamlit as st
import pandas as pd
import numpy as np
import pickle

# ---------------- PAGE CONFIG ---------------- #

st.set_page_config(page_title="Cancer Risk Prediction",layout="wide")

# ---------------- LOAD MODEL ---------------- #

with open("cancer-risk-prediction/model/Finalmodel.pk1", "rb") as file:
    model = pickle.load(file)

# ---------------- CUSTOM CSS ---------------- #

st.markdown("""
<style>

.main {
    background-color: #f5f7fa;
}

.title {
    text-align: center;
    color: #1565c0;
    font-size: 40px;
    font-weight: bold;
}

.subtitle {
    text-align: center;
    color: #666666;
    font-size: 18px;
}

.stButton > button {
    width: 100%;
    background-color: #1565c0;
    color: white;
    font-size: 18px;
    border-radius: 10px;
    height: 50px;
}

</style>
""", unsafe_allow_html=True)

# ---------------- HEADER ---------------- #

st.markdown(
    '<p class="title">🏥 Cancer Risk Prediction System</p>',
    unsafe_allow_html=True
)

st.markdown('<p class="subtitle">Early Cancer Risk Screening</p>',unsafe_allow_html=True)

st.divider()

# ---------------- INPUT FORM ---------------- #

col1, col2 = st.columns(2)

with col1:

    Age = st.number_input("Age",min_value=20,max_value=80,value=20)

    Gender = st.radio("Gender",["Female", "Male"])

    BMI = st.slider("BMI",min_value=10.0,max_value=50.0,value=25.0,step=0.1)

    Smoking = st.radio("Smoking Habit",["No", "Yes"])

with col2:

    Genetic = st.selectbox("Genetic Risk",[0, 1, 2])

    Physical_Activity = st.slider("Physical Activity",min_value=0.0,max_value=10.0,value=5.0,step=0.1)

    Alcohol_Intake = st.slider("Alcohol Intake",min_value=0.0,max_value=10.0,value=2.0,step=0.1)

    Cancer = st.radio("Family Cancer History",["No", "Yes"])

# ---------------- ENCODING ---------------- #

Gender = 0 if Gender == "Female" else 1

Smoking = 1 if Smoking == "Yes" else 0

Cancer = 1 if Cancer == "Yes" else 0

# ---------------- FEATURE ARRAY ---------------- #

features = np.array([
    Age,Gender,BMI,Smoking,Genetic,Physical_Activity,Alcohol_Intake,Cancer]).reshape(1, -1)

# ---------------- PREDICTION ---------------- #

if st.button("🔍 Predict Cancer Risk"):

    prediction = model.predict(features)

    if prediction[0] == 1:

        st.markdown("""
        <div style="
            background-color:#ffebee;
            padding:20px;
            border-radius:10px;
            color:#c62828;
            text-align:center;
            font-size:24px;
            font-weight:bold;">
            ⚠️ HIGH CANCER RISK DETECTED
            <br><br>
            Immediate medical consultation recommended.
        </div>
        """, unsafe_allow_html=True)

    else:

        st.markdown("""
        <div style="
            background-color:#e8f5e9;
            padding:20px;
            border-radius:10px;
            color:#2e7d32;
            text-align:center;
            font-size:24px;
            font-weight:bold;">
            ✅ LOW CANCER RISK
            <br><br>
            Continue maintaining a healthy lifestyle.
        </div>
        """, unsafe_allow_html=True)

# ---------------- FOOTER ---------------- #

st.divider()

st.caption(
    "Disclaimer: This prediction is generated by a Machine Learning model and should not replace professional medical diagnosis.")
